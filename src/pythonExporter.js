/**
 * Python export (SciPy odeint). Equations are printed from the same AST the
 * app simulates. odeint is an adaptive LSODA solver, so results agree with
 * the app's fixed-step Euler/RK4 only within numerical tolerance.
 */
import { prepareExport, commentBlock, fmt } from './domain/export/common.js';
import { toPython, makeSafeNamer, PYTHON_RESERVED } from './domain/export/printers.js';

export const generatePythonCode = (nodes, edges, timeStep = 0.1, maxTime = 100, visibleVariables = null, config = {}) => {
  const prep = prepareExport(nodes, edges, { dt: timeStep, stop: maxTime, ...config });
  if (!prep.ok) {
    return `${commentBlock('#', [
      'System Dynamics Studio — Python export',
      '',
      'This model cannot be exported yet. Fix these problems first:',
      ...prep.reasons.map((r) => `  - ${r}`),
    ])}\n`;
  }
  const { cfg, grid, domain, compiled, params, initial, parameters, computed, stocks, methodLabel } = prep;
  const safe = makeSafeNamer(PYTHON_RESERVED);
  domain.elements.forEach((e) => safe(e.name));
  const paramIds = new Set(compiled.parameterIds);
  const nameToId = compiled.nameToId;
  const sym = (dict) => (name) => {
    if (name === 'time' && !nameToId.has(name)) return undefined;
    const id = nameToId.get(name);
    if (id === undefined) return undefined;
    return paramIds.has(id) ? `${dict}['${safe(name)}']` : safe(name);
  };
  const eq = (id, dict) => toPython(compiled.asts.get(id), sym(dict), 't');

  const timeExpr = grid.partialStep
    ? `np.append(${fmt(cfg.start)} + ${fmt(cfg.dt)} * np.arange(${grid.fullSteps + 1}), ${fmt(cfg.stop)})`
    : `np.linspace(${fmt(cfg.start)}, ${fmt(cfg.stop)}, ${grid.fullSteps + 1})`;

  const lines = [];
  lines.push(commentBlock('#', [
    'Generated by System Dynamics Studio',
    `Model time: ${fmt(cfg.start)} to ${fmt(cfg.stop)} ${cfg.timeUnit || '(time unit not set)'}, output every ${fmt(cfg.dt)}`,
    `In-app solver: ${methodLabel}, fixed dt = ${fmt(cfg.dt)}.`,
    'This script integrates with scipy.integrate.odeint (adaptive LSODA), so values',
    'match the app within numerical tolerance, not digit for digit.',
  ]));
  lines.push('import numpy as np', 'from scipy.integrate import odeint', 'import matplotlib.pyplot as plt', '');
  lines.push('# Time functions (discontinuous; same definitions as in the app)');
  lines.push('def sd_step(height, start, t):\n    return np.where(t >= start, height, 0.0)\n');
  lines.push('def sd_ramp(slope, start, *rest):\n    *end, t = rest\n    until = np.minimum(t, end[0]) if end else t\n    return np.where(t > start, slope * (until - start), 0.0)\n');
  lines.push('def sd_pulse(height, start, width, t):\n    return np.where((t >= start) & (t < start + width), height, 0.0)\n');

  lines.push('# 1. Model Parameters (Constants)', 'params = {');
  parameters.forEach((p, i) => lines.push(`    '${safe(p.name)}': ${fmt(params[p.id])}${i === parameters.length - 1 ? '' : ','}${p.unit ? `  # ${p.unit}` : ''}`));
  lines.push('}', '');

  lines.push('# 2. Initial State (Stocks)', 'y0 = [');
  stocks.forEach((s, i) => lines.push(`    ${fmt(initial[i])}${i === stocks.length - 1 ? '' : ','}  # ${safe(s.name)}${s.unit ? ` [${s.unit}]` : ''}`));
  lines.push(']', '');

  lines.push('# 3. Model Definition', 'def model(y, t, p):', '    # Unpack stocks');
  lines.push(stocks.length === 1 ? `    ${safe(stocks[0].name)} = y[0]` : `    ${stocks.map((s) => safe(s.name)).join(', ')} = y`);
  lines.push('', '    # Auxiliaries & Flows (dependency order)');
  computed.forEach((c) => lines.push(`    ${safe(c.name)} = ${eq(c.id, 'p')}`));
  lines.push('', '    # Derivatives (Change in Stocks)');
  stocks.forEach((s) => {
    const terms = [...s.inflows.map((f) => `+ ${safe(domain.byId.get(f).name)}`), ...s.outflows.map((f) => `- ${safe(domain.byId.get(f).name)}`)];
    lines.push(`    d${safe(s.name)}_dt = ${terms.join(' ').replace(/^\+ /, '') || '0'}`);
  });
  lines.push(`\n    return [${stocks.map((s) => `d${safe(s.name)}_dt`).join(', ')}]`, '');

  lines.push('# 4. Run Simulation', `t = ${timeExpr}`, 'sol = odeint(model, y0, t, args=(params,), rtol=1e-8, atol=1e-10)', '');
  lines.push('# 5. Post-Processing (Calculate variables for plotting)');
  stocks.forEach((s, i) => lines.push(`${safe(s.name)} = sol[:, ${i}]`));
  parameters.forEach((p) => lines.push(`${safe(p.name)} = np.full_like(t, params['${safe(p.name)}'])`));
  computed.forEach((c) => lines.push(`${safe(c.name)} = ${eq(c.id, 'params')} + np.zeros_like(t)`));

  const plotted = (visibleVariables || stocks.map((s) => s.name)).filter((n) => nameToId.has(n));
  lines.push('', '# 6. Visualization', 'plt.figure(figsize=(10, 6))');
  plotted.forEach((n) => lines.push(`plt.plot(t, ${safe(n)}, label='${n}', linewidth=2)`));
  lines.push(
    '',
    "plt.title('System Dynamics Simulation (Python)')",
    `plt.xlabel('Time${cfg.timeUnit ? ` (${cfg.timeUnit})` : ''}')`,
    "plt.ylabel('Value')",
    'plt.legend()',
    'plt.grid(True, alpha=0.3)',
    'plt.tight_layout()',
    'plt.show()',
    '',
  );
  return lines.join('\n');
};
