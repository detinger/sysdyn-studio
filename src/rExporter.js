/**
 * R export (deSolve). Uses deSolve's fixed-step "rk4" or "euler" method on
 * the app's own time grid, so results should reproduce the app's run.
 */
import { prepareExport, commentBlock, fmt } from './domain/export/common.js';
import { toR, makeSafeNamer, R_RESERVED } from './domain/export/printers.js';

export const generateRCode = (nodes, edges, timeStep = 0.1, maxTime = 100, visibleVariables = null, config = {}) => {
  const prep = prepareExport(nodes, edges, { dt: timeStep, stop: maxTime, ...config });
  if (!prep.ok) {
    return `${commentBlock('#', [
      'System Dynamics Studio — R export',
      '',
      'This model cannot be exported yet. Fix these problems first:',
      ...prep.reasons.map((r) => `  - ${r}`),
    ])}\n`;
  }
  const { cfg, grid, domain, compiled, params, initial, parameters, computed, stocks, methodLabel } = prep;
  const safe = makeSafeNamer(R_RESERVED);
  domain.elements.forEach((e) => safe(e.name));
  const nameToId = compiled.nameToId;
  const sym = (name) => (nameToId.has(name) ? safe(name) : undefined);
  const eq = (id) => toR(compiled.asts.get(id), sym, 't');
  const method = cfg.method === 'euler' ? 'euler' : 'rk4';
  const times = grid.partialStep
    ? `c(seq(${fmt(cfg.start)}, by = ${fmt(cfg.dt)}, length.out = ${grid.fullSteps + 1}), ${fmt(cfg.stop)})`
    : `seq(${fmt(cfg.start)}, by = ${fmt(cfg.dt)}, length.out = ${grid.fullSteps + 1})`;

  const lines = [];
  lines.push(commentBlock('#', [
    'Generated by System Dynamics Studio',
    `Model time: ${fmt(cfg.start)} to ${fmt(cfg.stop)} ${cfg.timeUnit || '(time unit not set)'}`,
    `Solver: deSolve method "${method}" with fixed dt = ${fmt(cfg.dt)} (same as the app's ${methodLabel} run).`,
    'Required packages: install.packages(c("deSolve", "ggplot2", "tidyr"))',
  ]));
  lines.push('library(deSolve)', 'library(ggplot2)', 'library(tidyr)', '');
  lines.push('# Time functions (discontinuous; same definitions as in the app)');
  lines.push('sd_step <- function(height, start, t) ifelse(t >= start, height, 0)');
  lines.push('sd_ramp <- function(slope, start, end = Inf, t) ifelse(t > start, slope * (pmin(t, end) - start), 0)');
  lines.push('sd_pulse <- function(height, start, width, t) ifelse(t >= start & t < start + width, height, 0)', '');

  lines.push('# 1. Model Parameters', 'params <- c(');
  parameters.forEach((p, i) => lines.push(`  ${safe(p.name)} = ${fmt(params[p.id])}${i === parameters.length - 1 ? '' : ','}${p.unit ? `  # ${p.unit}` : ''}`));
  lines.push(')', '');
  lines.push('# 2. Initial State (Stocks)', 'init_state <- c(');
  stocks.forEach((s, i) => lines.push(`  ${safe(s.name)} = ${fmt(initial[i])}${i === stocks.length - 1 ? '' : ','}${s.unit ? `  # ${s.unit}` : ''}`));
  lines.push(')', '');

  lines.push('# 3. Model Definition', 'model_fn <- function(t, state, params) {', '  with(as.list(c(state, params)), {', '    # Auxiliaries & Flows (dependency order)');
  computed.forEach((c) => lines.push(`    ${safe(c.name)} <- ${eq(c.id)}`));
  lines.push('', '    # Change in Stocks (Derivatives)');
  stocks.forEach((s) => {
    const terms = [...s.inflows.map((f) => `+ ${safe(domain.byId.get(f).name)}`), ...s.outflows.map((f) => `- ${safe(domain.byId.get(f).name)}`)];
    lines.push(`    d_${safe(s.name)} <- ${terms.join(' ').replace(/^\+ /, '') || '0'}`);
  });
  const extras = [...computed, ...parameters].map((v) => `${safe(v.name)} = ${safe(v.name)}`);
  lines.push(`\n    return(list(c(${stocks.map((s) => `d_${safe(s.name)}`).join(', ')})${extras.length ? `,\n                ${extras.join(',\n                ')}` : ''}))`);
  lines.push('  })', '}', '');

  lines.push('# 4. Run Simulation', `times <- ${times}`, `out <- ode(y = init_state, times = times, func = model_fn, parms = params, method = "${method}")`, '');
  lines.push('# 5. Visualization', 'out_df <- as.data.frame(out)', '', '# Pivot to long format for ggplot', 'out_long <- pivot_longer(out_df, cols = -time, names_to = "variable", values_to = "value")');
  if (visibleVariables && visibleVariables.length) {
    const vars = visibleVariables.filter((n) => nameToId.has(n)).map((n) => `"${safe(n)}"`);
    lines.push('', '# Filter for variables requested in the UI', `out_long <- out_long[out_long$variable %in% c(${vars.join(', ')}), ]`);
  }
  lines.push(
    '',
    'ggplot(out_long, aes(x = time, y = value, color = variable)) +',
    '  geom_line(linewidth = 1) +',
    '  theme_minimal() +',
    '  labs(title = "System Dynamics Simulation (R)",',
    '       subtitle = "Generated via System Dynamics Studio",',
    `       x = "Time${cfg.timeUnit ? ` (${cfg.timeUnit})` : ''}", y = "Value") +`,
    '  theme(legend.position = "bottom")',
    '',
  );
  return lines.join('\n');
};
